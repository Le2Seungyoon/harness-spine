#!/usr/bin/env python3
"""Tests for check_rules_size.py — run: python3 test_check_rules_size.py

A hook is code, so it ships with a test (`enforcement.md` -> Hook contracts). Both halves
matter: the must-block half proves the check fires, the must-pass half is what keeps false
positives from creeping in. A test that only ever asserts "it blocked" cannot notice the day
the hook starts blocking everything.

The hook SCANS the governed set and ignores the payload, so each scenario needs its own tree:
one over-budget file anywhere makes the whole scan speak. `CLAUDE_PROJECT_DIR` points the hook
at that tree — the hook derives the root from `__file__` otherwise, which would scan this repo.

Stdlib only, no test runner: the hook must be verifiable in a freshly scaffolded repo that
has no dev dependencies installed yet.
"""
import contextlib
import json
import os
import subprocess
import sys
import tempfile

HOOK = os.path.join(os.path.dirname(os.path.abspath(__file__)), "check_rules_size.py")
BUDGET = 150
GENERATED_HEADER = "<!-- GENERATED by .agents/hooks/build-inventory.py — do not edit by hand -->"

failures = []


def run(root, payload="", raw=False):
    """Feed the hook a payload (or garbage, or nothing); return (advisory_text, returncode)."""
    env = dict(os.environ, CLAUDE_PROJECT_DIR=root)
    proc = subprocess.run(
        [sys.executable, HOOK],
        input=payload if raw else json.dumps(payload) if payload else "",
        capture_output=True,
        text=True, encoding="utf-8",
        env=env,
        timeout=10,  # stays below the hook's own timeout in settings.json
    )
    out = proc.stdout.strip()
    msg = json.loads(out)["hookSpecificOutput"]["additionalContext"] if out else ""
    return msg, proc.returncode


def check(name, condition, detail=""):
    print(("PASS  " if condition else "FAIL  ") + name + (f"  ({detail})" if detail and not condition else ""))
    if not condition:
        failures.append(name)


def write(root, relpath, n_lines, first_line=None, line_text="line\n"):
    path = os.path.join(root, relpath.replace("/", os.sep))
    os.makedirs(os.path.dirname(path) or root, exist_ok=True)
    body = line_text * n_lines
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"{first_line}\n{body}" if first_line else body)
    return path


def write_raw(root, relpath, text):
    """Exact contents, so a test can pin a byte count instead of a line count."""
    path = os.path.join(root, relpath.replace("/", os.sep))
    os.makedirs(os.path.dirname(path) or root, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return path


@contextlib.contextmanager
def tree(**files):
    """A throwaway project root. `files` maps a relpath -> line count, or (lines, first_line)."""
    with tempfile.TemporaryDirectory() as root:
        os.makedirs(os.path.join(root, ".agents", "rules"), exist_ok=True)
        for rel, spec in files.items():
            n, first = spec if isinstance(spec, tuple) else (spec, None)
            write(root, rel.replace("__", "/"), n, first)
        yield root


def payload(tool="Write", path=".agents/rules/over.md"):
    body = {"hook_event_name": "PostToolUse", "tool_name": tool}
    if path:
        body["tool_input"] = {"file_path": path}
    return body


def main():
    # --- byte budget: the half that exists because Codex measures in bytes -------------
    # A line-only check reads a dense file as smaller than it is. These pin the gap.
    with tree() as root:
        write(root, ".agents/rules/dense.md", 40, line_text="x" * 400 + "\n")
        msg, _ = run(root, json.dumps(payload()))
        check("short-but-dense file nudges on bytes", "bytes" in msg, msg[:90])
        check("byte nudge reports the real byte count", "16,040 bytes" in msg, msg[:90])
        check("byte-only overrun does not claim a line overrun",
              "lines vs" not in msg, msg[:90])
        check("authored advice includes semantic routing review",
              all(s in msg for s in ("AGENTS.md", "descriptions", "read triggers", "cross-references")), msg)
        check("routing review is not claimed by link checks",
              "link existence" in msg and "semantic" in msg, msg)

    # Discrimination: this file is UNDER budget by characters and OVER by bytes. If the
    # hook ever counts characters again, this is the test that goes red -- Korean is
    # 3 bytes/char in UTF-8, and this repo's docs are half Korean.
    korean = ("한글" * 2000) + "\n"            # 4,000 chars, 12,001 bytes
    with tree() as root:
        write_raw(root, ".agents/rules/korean.md", korean)
        msg, _ = run(root, json.dumps(payload()))
        check("Korean file over budget in BYTES is caught", "12,001 bytes" in msg, msg[:90])
        check("...and it is under budget by CHARACTER count",
              len(korean) < 10240 and len(korean.encode()) > 10240, f"{len(korean)} chars")

    with tree() as root:
        write_raw(root, ".agents/rules/ok.md", "x" * 10240)   # exactly at budget: passing
        msg, code = run(root, json.dumps(payload()))
        check("file exactly at the byte budget is silent", msg == "", msg[:90])
        check("file exactly at the byte budget exits 0", code == 0, f"exit={code}")

    with tree(**{".agents__rules__both.md": BUDGET + 50}) as root:
        write(root, ".agents/rules/both.md", BUDGET + 50, line_text="y" * 100 + "\n")
        msg, _ = run(root, json.dumps(payload()))
        check("a file over BOTH budgets reports both",
              "lines vs" in msg and "bytes vs" in msg, msg[:120])

    # --- Codex project-doc cliff: correctness, not style ------------------------------
    # AGENTS.md alone, against project_doc_max_bytes. Sizes here stay under the soft
    # budgets so a failure can only come from the cliff check.
    with tree() as root:
        write_raw(root, ".codex/config.toml", "project_doc_max_bytes = 2000\n")
        write_raw(root, "AGENTS.md", "z" * 3000)
        msg, code = run(root, json.dumps(payload()))
        check("AGENTS.md over the declared Codex limit nudges", "3,000 bytes" in msg, msg[:120])
        check("...names the declared limit, not the fallback",
              "2,000" in msg and "32,768" not in msg, msg[:120])
        check("...says the truncation is silent", "truncates" in msg, msg[:120])
        check("...still exits 0", code == 0, f"exit={code}")

    with tree() as root:
        write_raw(root, ".codex/config.toml", "project_doc_max_bytes = 2000\n")
        write_raw(root, "AGENTS.md", "z" * 1700)          # 85% -- warn before the cliff
        msg, _ = run(root, json.dumps(payload()))
        check("AGENTS.md approaching the cliff warns early", "85%" in msg, msg[:120])

    with tree() as root:
        # No .codex/config.toml. 30,000 B is past 80% of the 32,768 fallback (and past the
        # soft byte budget too) -- both notes should appear, each naming its own limit.
        write_raw(root, "AGENTS.md", "z" * 30000)
        msg, _ = run(root, json.dumps(payload()))
        check("undeclared limit falls back and says so", "32,768" in msg, msg[:150])
        check("...and the soft byte budget still reports separately",
              "10,240" in msg, msg[:150])

    with tree() as root:
        write_raw(root, ".codex/config.toml", "project_doc_max_bytes = 65536\n")
        write_raw(root, "AGENTS.md", "z" * 3000)
        msg, _ = run(root, json.dumps(payload()))
        check("AGENTS.md well under the cliff is silent", msg == "", msg[:120])


    # --- must-block half: the nudge has to fire, and say something usable ---
    with tree(**{".agents__rules__over.md": BUDGET + 50}) as root:
        msg, rc = run(root, payload())
        check("over-budget rules file nudges", bool(msg), "silent")
        check("nudge reports the real line count", str(BUDGET + 50) in msg, msg[:60])
        check("nudge names the file", "over.md" in msg, msg[:60])
        check("nudge names the four options", all(w in msg for w in ("RELOCATE", "SPLIT", "ABSTRACT", "COMPRESS")), msg[:60])
        check("nudge cites the rule file it enforces", "workflow.md" in msg, msg[:60])
        # Rules route through the AGENTS.md read triggers, not `paths:` frontmatter
        # (runtime.md -> Rule delivery), so SPLIT must not point at a mechanism this repo dropped.
        check("SPLIT gates on an AGENTS.md read trigger, not a paths: glob",
              "paths:" not in msg and "own read trigger in the AGENTS.md" in msg, msg[:400])
        check("advisory: exit code stays 0", rc == 0, f"rc={rc}")

        # The regression this hook exists to prevent: the payload must not gate the check.
        # An edit made with sed / a heredoc / a python one-liner arrives as a Bash call with
        # no file_path at all, and used to slip past in silence.
        check("Bash edit (no file_path) still nudges", bool(run(root, payload("Bash", path=None))[0]))
        check("payload naming an unrelated file still nudges", bool(run(root, payload("Write", "src/main.py"))[0]))
        check("non-JSON payload still nudges", bool(run(root, "not json at all", raw=True)[0]))
        check("empty stdin still nudges", bool(run(root)[0]))
        check("garbage payload still exits 0", run(root, "not json at all", raw=True)[1] == 0)

    with tree(**{"AGENTS.md": BUDGET + 1}) as root:
        check("over-budget AGENTS.md nudges", bool(run(root, payload())[0]))

    # --- generated files: the four options do not apply to them ---
    with tree(**{".agents__rules__ledger.md": (BUDGET + 50, GENERATED_HEADER)}) as root:
        msg, _ = run(root, payload())
        check("over-budget generated file nudges", bool(msg), "silent")
        check("generated file gets the generator advice", "GENERATED" in msg and "generator" in msg, msg[:80])
        check("generated file is NOT told to run the compression skill", "refactor-agent-rules" not in msg, msg[:80])

    with tree(**{
        ".agents__rules__ledger.md": (BUDGET + 50, GENERATED_HEADER),
        ".agents__rules__workflow.md": BUDGET + 10,
    }) as root:
        msg, _ = run(root, payload())
        check("mixed over-budget set gets both advices", "refactor-agent-rules" in msg and "generator" in msg, msg[:80])

    # --- must-pass half: everything below is legitimate work and must stay silent ---
    with tree(**{
        ".agents__rules__under.md": BUDGET - 50,
        ".agents__rules__edge.md": BUDGET,  # exactly at budget: still passing
        ".agents__rules__ledger.md": (BUDGET - 1, GENERATED_HEADER),
        "AGENTS.md": BUDGET - 1,
        "src__big_module.py": BUDGET + 500,
        "docs__2026-01-01-notes.md": BUDGET + 500,
    }) as root:
        msg, rc = run(root, payload())
        check("clean governed set is silent", msg == "", msg[:80])
        check("clean tree exits 0", rc == 0, f"rc={rc}")

    # --- scope stays narrow: `.agents/` also holds hooks, skills and agents (2026-10-23) ---
    # The harness keeps code in `.agents/hooks/` beside `.agents/rules/`; a widened glob
    # (`.agents/**/*.md`) would start budgeting test fixtures and skill bodies.
    with tree(**{
        ".agents__rules__ok.md": BUDGET - 1,
        ".agents__hooks__notes.md": BUDGET + 500,
        ".agents__skills__s__SKILL.md": BUDGET + 500,
        ".agents__agents__lane.md": BUDGET + 500,
    }) as root:
        msg, _ = run(root, payload())
        check("only .agents/rules + AGENTS.md are governed (hooks/skills/agents ignored)", msg == "", msg[:80])

    # --- silence must mean exactly one thing: checked and passing ---
    with tempfile.TemporaryDirectory() as root:  # no .agents/rules, no AGENTS.md
        msg, rc = run(root, payload())
        check("empty governed set says so instead of passing quietly", "EMPTY" in msg, msg[:80] or "silent")
        check("empty governed set still exits 0", rc == 0, f"rc={rc}")

    with tree(**{".agents__rules__ok.md": BUDGET - 1}) as root:
        os.mkdir(os.path.join(root, ".agents", "rules", "trap.md"))  # a directory, not a file
        msg, rc = run(root, payload())
        check("unreadable governed entry says so instead of passing quietly", "NOT checked" in msg, msg[:80] or "silent")
        check("unreadable governed entry still exits 0", rc == 0, f"rc={rc}")

    # --- run by hand: an open stdin that never delivers must not hang the hook (2026-09-17) ---
    with tree(**{".agents__rules__ok.md": BUDGET - 1}) as root:
        proc = subprocess.Popen([sys.executable, HOOK], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                env=dict(os.environ, CLAUDE_PROJECT_DIR=root))
        try:
            rc = proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            proc.kill()
            rc = None
        proc.stdin.close()
        proc.stdout.close()
        check("an open, silent stdin does not block the hook", rc == 0, f"rc={rc}")

    print()
    if failures:
        print(f"{len(failures)} FAILED: " + ", ".join(failures))
        sys.exit(1)
    print("all checks passed")


if __name__ == "__main__":
    main()
